CREATE TABLE `scraping_infos` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `keyword` VARCHAR(200) NULL,
    `type` VARCHAR(100) NULL,
    `sub_type` VARCHAR(100) NULL,
    `title` VARCHAR(500) NULL,
    `province` VARCHAR(100) NULL,
    `city` VARCHAR(100) NULL,
    `district` VARCHAR(100) NULL,
    `detail` TEXT NULL,
    `published_at` DATETIME(3) NULL,
    `bid_doc_fetched_at` DATETIME(3) NULL,
    `project_no` VARCHAR(100) NULL,
    `project_budget` VARCHAR(100) NULL,
    `winning_amount` VARCHAR(100) NULL,
    `bidding_method` VARCHAR(100) NULL,
    `project_owner` VARCHAR(255) NULL,
    `owner_contact` VARCHAR(100) NULL,

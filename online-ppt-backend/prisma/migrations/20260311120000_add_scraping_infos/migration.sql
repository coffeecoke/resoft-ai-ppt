    `product_related` VARCHAR(500) NULL,
    `reserve1` VARCHAR(500) NULL,
    `reserve2` VARCHAR(500) NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at` DATETIME(3) NOT NULL,

    INDEX `idx_scraping_keyword`(`keyword`),
    INDEX `idx_scraping_type`(`type`),
    INDEX `idx_scraping_province`(`province`),
    INDEX `idx_scraping_city`(`city`),
    INDEX `idx_scraping_published_at`(`published_at`),
    INDEX `idx_scraping_bid_deadline`(`bid_deadline`),
